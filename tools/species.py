def kt(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def write_kotlin():
    root = Path(__file__).resolve().parent.parent
    out = root / "app/src/main/java/app/roamling/domain/Catalog.kt"
    lines = ["package app.roamling.domain", "", "// Generated by tools/species.py – edit there.", "", "val SPECIES: List<Species> = listOf("]
    for s in SPECIES:
        forms = ", ".join(f"Form(Taste.{t.upper()}, {kt(ru)}, {kt(en)})" for t, ru, en, _ in s.forms)
        when = f"Wild.{s.when.upper()}" if s.when else "null"
        lines.append(f"    Species({kt(s.id)}, {kt(s.ru)}, {kt(s.en)}, Group.{s.group.upper()}, {s.pace}, listOf({forms}), {when}, {kt(s.about_ru)}, {kt(s.about_en)}),")
    lines.append(")")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    write_kotlin()
